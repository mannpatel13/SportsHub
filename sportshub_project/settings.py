# In production, Render/another host supplies SECRET_KEY. The fallback keeps
# local development working without requiring an environment variable.
SECRET_KEY = os.environ.get(
    'SECRET_KEY',
    'django-insecure-sportshub-local-development-key-change-in-production'
)

DEBUG = os.environ.get('DJANGO_DEBUG', 'True').lower() == 'true'

# Render supplies RENDER_EXTERNAL_HOSTNAME automatically. For other hosts,
# provide ALLOWED_HOSTS as a comma-separated environment variable.
_allowed_hosts = os.environ.get('ALLOWED_HOSTS', '')
ALLOWED_HOSTS = [h.strip() for h in _allowed_hosts.split(',') if h.strip()]
render_hostname = os.environ.get('RENDER_EXTERNAL_HOSTNAME')
if render_hostname and render_hostname not in ALLOWED_HOSTS:
    ALLOWED_HOSTS.append(render_hostname)
if DEBUG and not ALLOWED_HOSTS:
    ALLOWED_HOSTS = ['localhost', '127.0.0.1']

CSRF_TRUSTED_ORIGINS = [
    origin.strip()
    for origin in os.environ.get('CSRF_TRUSTED_ORIGINS', '').split(',')
    if origin.strip()
]
if render_hostname:
    render_origin = f'https://{render_hostname}'
    if render_origin not in CSRF_TRUSTED_ORIGINS:
        CSRF_TRUSTED_ORIGINS.append(render_origin)

